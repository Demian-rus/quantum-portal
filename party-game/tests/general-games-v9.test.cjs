'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const api=require('../scripts/content.cjs');
const deferred=JSON.parse(fs.readFileSync(path.join(__dirname,'../content/editorial/general-games-audience-v1-decisions.json'),'utf8'));
test('VG9 broad 50 gaming prompts: full-source exact dedup, correct types, pinned version and VG6 reserves',()=>{
 const d=api.readDataset();
 const prev=d.packs.find(p=>p.id==='general'&&p.version===58),now=d.packs.find(p=>p.id==='general'&&p.version===59);
 assert.ok(prev&&now);
 const fresh=d.cards.filter(c=>c.pack==='general-games-v9'),ids=fresh.map(c=>c.id);
 assert.equal(fresh.length,50);
 assert.equal(fresh.filter(c=>c.type==='word').length,40);
 assert.equal(fresh.filter(c=>c.type==='phrase').length,10);
 assert.equal(fresh.filter(c=>c.difficulty==='easy').length,43);
 assert.equal(fresh.filter(c=>c.difficulty==='medium').length,7);
 assert.equal(fresh.filter(c=>c.difficulty==='hard').length,0);
 assert.ok(fresh.every(c=>c.categories.length===1&&c.categories[0]==='videogames'&&c.meta?.recognition==='broad'));
 assert.ok(fresh.every(c=>/^[А-ЯЁ -]+$/u.test(c.text)&&/^[А-ЯЁ -]+$/u.test(c.meta.game)));
 assert.ok(fresh.every(c=>c.type==='word'?!/\s/u.test(c.text):/\s/u.test(c.text)));
 assert.ok(fresh.every(c=>/^word-081\d{3}$|^phrase-081\d{3}$/.test(c.id)));
 const previousTexts=new Set(d.cards.filter(c=>c.pack!=='general-games-v9').map(c=>api.normalize(c.text)));
 assert.equal(new Set(ids).size,50);
 assert.equal(new Set(fresh.map(c=>api.normalize(c.text))).size,50);
 for(const c of fresh)assert.ok(!previousTexts.has(api.normalize(c.text)),'Historical source duplicate '+c.text);
 assert.equal(prev.criteria.cardIds.length,7219);
 assert.equal(now.criteria.cardIds.length,7269);
 assert.deepEqual(now.criteria.cardIds.slice(0,7219),prev.criteria.cardIds);
 assert.deepEqual(now.criteria.cardIds.slice(7219),ids);
 assert.equal(new Set(now.criteria.cardIds).size,7269);
 const reserved=deferred.entries.filter(x=>x.decision==='reserve-for-theme').map(x=>x.id);
 assert.equal(reserved.length,151);
 assert.ok(reserved.every(id=>!now.criteria.cardIds.includes(id)));
 const result=api.validate(d);
 assert.equal(result.errors.length,0,JSON.stringify(result.errors));
});
